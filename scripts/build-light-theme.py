#!/usr/bin/env python3
"""Generate frontend/src/light.css from the dark frontend/src/styles.css.

Usage: python3 scripts/build-light-theme.py

Every rule with a colour gets a `:root[data-theme=light]` twin whose colours are
remapped by role: backgrounds become light surfaces (keeping their elevation
order, so panels stay lighter than the page), text becomes dark, borders become
soft greys, and saturated accents are darkened enough to read on white.
Hand-tuned overrides live in LIGHT_EXTRAS. Re-run after changing styles.css.
"""
import colorsys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'frontend/src/styles.css'
OUT = ROOT / 'frontend/src/light.css'
PREFIX = ':root[data-theme=light]'
COLOUR = re.compile(r'#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b')
BACKGROUND = {'background', 'background-color'}
BORDER = {'border', 'border-color', 'border-top', 'border-bottom', 'border-left', 'border-right', 'border-top-color',
          'border-bottom-color', 'outline', 'box-shadow', 'text-decoration-color'}
LIGHT_EXTRAS = '''
:root[data-theme=light]{color-scheme:light;color:#18212b;background:#eef1f5;--mint:#0f8a6c;--muted:#5d6a78;--border:#d5dce4;--panel:#ffffff}
:root[data-theme=light] body{background:#eef1f5}
:root[data-theme=light] .map-container .maplibregl-canvas{filter:saturate(.35) brightness(1.03)}
:root[data-theme=light] .line-chip{box-shadow:0 1px 3px #0002}
:root[data-theme=light] .status-badge.new,:root[data-theme=light] .new-foot{background:#0f8a6c;color:#fff}
:root[data-theme=light] .status-badge.new i{background:#fff}
:root[data-theme=light] .answer p{color:#22303a}
:root[data-theme=light] .chat-turn .answer.broken p{color:#2e2546}
:root[data-theme=light] .maplibregl-ctrl-attrib{background:#ffffffd9!important;color:#3a4651!important}
:root[data-theme=light] .maplibregl-ctrl-attrib a{color:#0f6e57}
'''


def parse(hex_colour):
    h = hex_colour[1:]
    if len(h) in (3, 4):
        h = ''.join(c * 2 for c in h)
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return r, g, b, h[6:8]


def build(r, g, b, alpha):
    return '#' + ''.join(f'{round(max(0, min(1, v)) * 255):02x}' for v in (r, g, b)) + alpha


def remap(hex_colour, role):
    r, g, b, alpha = parse(hex_colour)
    hue, light, sat = colorsys.rgb_to_hls(r, g, b)
    accent = sat > .35 and .3 < light < .9
    if role == 'background':
        if accent and light > .45:
            new = light  # badges, buttons and chips keep their colour
        elif light < .2:
            new = .93 + (light / .2) * .07  # page → panel → raised surface, all near white
        else:
            new = min(.97, 1.18 - light)  # hovers and tinted fills
        sat = min(sat, .45) if not accent else sat
    elif role == 'border':
        new = .72 + (.3 - min(light, .3))  # dark hairlines → soft grey
        new = max(.72, min(.9, new))
        if accent:
            new = min(new, .55)
    else:  # text and icons
        if accent:
            new = min(light, .36)  # darken mint, coral, violet for contrast on white
        else:
            new = max(.1, min(.48, 1 - light))
    return build(*colorsys.hls_to_rgb(hue, new, sat), alpha)


def convert(block):
    """Light twins of the colour declarations in a flat block of rules."""
    out = []
    for selectors, body in re.findall(r'([^{}]+)\{([^{}]*)\}', block):
        decls = []
        for decl in body.split(';'):
            if ':' not in decl or not COLOUR.search(decl):
                continue
            prop, value = (part.strip() for part in decl.split(':', 1))
            role = 'background' if prop in BACKGROUND else 'border' if prop in BORDER else 'text'
            decls.append(f'{prop}:{COLOUR.sub(lambda m: remap(m.group(), role), value)}')
        if decls:
            prefixed = ','.join(f'{PREFIX} {s.strip()}' if s.strip() not in (':root', 'html') else PREFIX for s in selectors.split(','))
            out.append(f'{prefixed}{{{";".join(decls)}}}')
    return out


def main():
    css = re.sub(r'@import[^;]+;', '', SOURCE.read_text())
    css = re.sub(r'@keyframes[^{]+\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}', '', css)  # animations keep their colours
    lines = []
    for match in re.finditer(r'(@media[^{]+)\{((?:[^{}]*\{[^{}]*\})*)[^{}]*\}|([^@{}][^{}]*\{[^{}]*\})', css):
        if match.group(1):
            inner = convert(match.group(2))
            if inner:
                lines.append(f'{match.group(1).strip()}{{{"".join(inner)}}}')
        else:
            lines.extend(convert(match.group(3)))
    OUT.write_text('/* Generated by scripts/build-light-theme.py from styles.css; edit LIGHT_EXTRAS there. */\n'
                   + '\n'.join(lines) + LIGHT_EXTRAS)
    print(f'{len(lines)} light rules written to {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
