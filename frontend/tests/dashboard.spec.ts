test('AI briefing and copilot answer with linked records',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.stack||e.message));
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('/');
 await expect(page.locator('tbody tr').first()).toBeVisible({timeout:30000});
 await page.getByRole('button',{name:/^Briefings/}).click();
 await expect(page.getByRole('heading',{name:'The accessibility briefing'})).toBeVisible();
 await expect(page.locator('.ai-report .source-chips button').first()).toBeVisible();
 const input=page.getByRole('textbox',{name:'Ask a question'});
 await expect(input).toBeEnabled();
 await input.fill('What is the status at Alexanderplatz?');
 await page.getByRole('button',{name:'Send question'}).click();
 await expect(input).toHaveValue('');
 await expect(page.locator('.bubble.user')).toHaveText('What is the status at Alexanderplatz?');
 const answer=page.locator('.answer').first();
 await expect(answer).toContainText('Alexanderplatz',{timeout:60000});
 await expect(answer).toContainText('do not establish a step-free route');
 await input.fill('What is the status at Yorckstraße?');
 await page.keyboard.press('Enter');
 await expect(page.locator('.answer').nth(1).locator('.no-lift')).toContainText('No elevator: S2, S25, S26',{timeout:60000});
 if(await page.evaluate(async()=>(await (await fetch('/api/dashboard')).json()).stations.find((s:{name:string;outages:number})=>s.name==='Alexanderplatz')?.outages>0))await expect(answer.getByRole('img',{name:/out of service/})).toBeVisible();
 await page.waitForTimeout(800);
 await page.screenshot({path:'../docs/screenshots/ai.png',fullPage:true});
 await answer.first().locator('.source-chips button').first().click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'DE',exact:true}).click();
 await expect(page.locator('html')).toHaveAttribute('lang','de');
 await expect(page.getByRole('heading',{name:'Das Barrierefreiheits-Briefing'})).toBeVisible();
 await expect(page.locator('.ai-report')).toContainText('kein vollständiges Inventar');
 await page.getByRole('button',{name:'Wie viele Aufzüge sind in Betrieb?'}).click();
 await expect(page.locator('.answer')).toContainText('Aufzugsstörungsmeldungen',{timeout:60000});
 await page.getByRole('textbox',{name:'Frage stellen'}).fill('Wann wird der Aufzug repariert?');
 await page.keyboard.press('Enter');
 await expect(page.locator('.bubble.user')).toHaveCount(2);
 await expect(page.locator('.answer').nth(1)).toContainText('keine Reparaturzeiten');
 await page.getByRole('button',{name:'EN',exact:true}).click();
 expect(errors).toEqual([]);
});
