import {test,expect} from '@playwright/test';
test('desktop network, directory, filters, details and map',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.stack||e.message));
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Berlin, without barriers.'})).toBeVisible();
 await expect(page.getByText('Live feed',{exact:true})).toBeVisible({timeout:30000});
 await expect(page.locator('tbody tr').first()).toBeVisible();
 await page.waitForTimeout(2500);
 await page.screenshot({path:'../docs/screenshots/desktop.png',fullPage:true});
 const help=page.getByRole('button',{name:'What does this mean?'});
 await help.click();
 await expect(help).toHaveAttribute('aria-expanded','true');
 await expect(page.locator('.stat-help-pop')).toContainText('Außer Betrieb');
 await page.keyboard.press('Escape');
 await expect(page.locator('.stat-help-pop')).toHaveCount(0);
 await page.getByRole('button',{name:'Explore all stations'}).click();
 await page.getByRole('textbox',{name:'Search stations'}).fill('Alexanderplatz');
 await expect(page.locator('tbody tr')).toHaveCount(1);
 await page.locator('.station-name').click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await expect(page.locator('.elevator-card').first()).toBeVisible();
 await expect(page.getByText('Observation history',{exact:true})).toBeVisible();
 await page.screenshot({path:'../docs/screenshots/station-detail.png',fullPage:true});
 await page.keyboard.press('Escape');
 await page.getByRole('textbox',{name:'Search stations'}).fill('Yorckstr');
 await page.locator('.station-name',{hasText:/^Yorckstr\.\d/}).click();
 await expect(page.getByRole('dialog').locator('div.no-lift')).toContainText('No elevator');
 await expect(page.getByRole('dialog').locator('div.no-lift .line-chip')).toHaveText(['S2','S25','S26']);
 await page.screenshot({path:'../docs/screenshots/no-elevator.png'});
 await page.keyboard.press('Escape');
 await page.getByRole('textbox',{name:'Search stations'}).fill('');
 await page.getByRole('checkbox',{name:'Without elevator'}).check();
 expect(await page.locator('tbody tr').count()).toBeGreaterThanOrEqual(20);
 await expect(page.locator('tbody tr',{hasText:'Nöldnerplatz'}).locator('.status-badge.no-lift')).toHaveText('No elevator');
 await page.getByRole('checkbox',{name:'Without elevator'}).uncheck();
 await page.getByRole('textbox',{name:'Search stations'}).fill('no-such-station-123');
 await expect(page.getByText('No stations match this view.')).toBeVisible();
 await page.getByRole('button',{name:'Clear search'}).click();
 await page.getByRole('combobox',{name:'Filter by network'}).selectOption('U-Bahn');
 await expect(page.locator('tbody tr').first()).toBeVisible();
 await page.getByRole('checkbox',{name:'Outages only'}).check();
 expect(await page.locator('.status-badge.offline').count()).toBeGreaterThan(0);
 await page.getByRole('checkbox',{name:'Outages only'}).uncheck();
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await expect(page.locator('.line-chip')).toHaveCount(25);
 await page.locator('.line-chip',{hasText:/^U2$/}).click();
 await expect(page.locator('.line-chip',{hasText:/^U2$/})).toHaveAttribute('aria-pressed','true');
 await page.getByRole('button',{name:'Berlin map',exact:true}).click();
 await expect(page.locator('.maplibregl-canvas')).toBeVisible();
 await expect(page.locator('.map-dot').first()).toBeVisible();
 const mapSearch=page.getByRole('textbox',{name:'Find a station on the map'});
 await mapSearch.fill('gneisenau');
 await page.getByRole('option',{name:/Gneisenaustraße/}).click();
 await expect(page.locator('.map-popup')).toHaveText('Gneisenaustraße · No elevator');
 await expect(page.locator('.maplibregl-marker.focused')).toHaveCount(1);
 await expect(page.locator('.maplibregl-marker.no-lift[aria-label^="Yorckstr. ·"]')).toHaveAttribute('aria-label',/Yorckstr\. · .*No elevator: S2, S25, S26/);
 await page.waitForTimeout(2000);
 await page.screenshot({path:'../docs/screenshots/map.png',fullPage:true});
 expect(errors).toEqual([]);
});
test('theme follows the system by default and can be chosen manually',async({page})=>{
 await page.emulateMedia({colorScheme:'light'});
 await page.goto('/');
 await expect(page.locator('html')).toHaveAttribute('data-theme','light');
 await page.emulateMedia({colorScheme:'dark'});
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.getByRole('button',{name:/^Theme: System/}).click();
 await page.getByRole('menuitemradio',{name:/^Light/}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','light');
 expect(await page.evaluate(()=>getComputedStyle(document.body).backgroundColor)).toBe('rgb(238, 241, 245)');
 await page.reload();
 await expect(page.locator('html')).toHaveAttribute('data-theme','light');
 await page.getByRole('button',{name:/^Theme: Light/}).click();
 await expect(page.getByRole('menuitemradio',{name:/^Daytime/})).toBeVisible();
 await page.getByRole('menuitemradio',{name:/^System/}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
});
